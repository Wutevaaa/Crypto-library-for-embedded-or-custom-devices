    void init(uint8_t* key, uint8_t* iv) {
        const uint8_t nonce[12] = {1,2,3,1,2,4,1,2,5,1,2,6};
        memcpy(p.nonce, nonce, 12);
        memcpy(p.rk, key, 32);
        p.ctr = 0;
        #ifdef __arm__
            AES_256_keyschedule(key, p.rk+32);
        #else
            #warning "This will not run on x86 (only on Cortex M3/4)"
        #endif
    }

    void encrypt(uint8_t* in, size_t size) {
        uint8_t* out[size];
        #ifdef __arm__
            AES_256_encrypt_ctr(&p, in, out, size);
        #else
            #warning "This will not run on x86 (only on Cortex M3/4)"
        #endif
        memcpy(in, out, size);
    }

